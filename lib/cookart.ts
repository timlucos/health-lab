/** Минуты из текста шага: «5–7 минут» → 7, «20 мин» → 20. */
export function stepMinutes(text: string): number | null {
  const m = text.match(/(\d+)(?:\s*[–-]\s*(\d+))?\s*(минут|мин\b|мин\.)/i);
  if (m) return Number(m[2] ?? m[1]);
  const h = text.match(/(\d+(?:[.,]\d+)?)\s*час/i);
  return h ? Math.round(Number(h[1].replace(",", ".")) * 60) : null;
}

/** Основа слова для поиска в тексте шага: «Куриное филе» → «курин», «Яйцо» → «яйц». */
const stem = (w: string) => w.toLowerCase().replace(/[^а-яё]/g, "").slice(0, Math.max(3, Math.min(5, w.length - 2)));

export function stepArt(text: string, ingredients: { name: string; key: string }[]) {
  const t = text.toLowerCase();
  const foods: string[] = [];
  for (const i of ingredients) {
    const e = FOOD_EMOJI[i.key];
    if (!e || foods.includes(e)) continue;
    const words = [i.key, ...i.name.split(/[\s,()]+/)].filter((w) => w.length >= 3).map(stem);
    if (words.some((w) => w.length >= 3 && t.includes(w))) foods.push(e);
  }
  const acts = ACTIONS.filter(([re]) => re.test(text)).slice(0, 2).map(([, e, l]) => ({ e, l }));
  return { foods: foods.slice(0, 5), acts, min: stepMinutes(text) };
}

/** Количество продукта на N порций, если в рецепте есть граммы. */
export function scaledQty(i: { qty: string; g: number; key: string }, factor: number): string {
  if (!i.g || factor === 1) return i.qty;
  const g = i.g * factor;
  const pcs = i.qty.match(/^(\d+(?:[.,]\d+)?)\s*шт/);
  if (pcs) return `${Math.max(1, Math.round(Number(pcs[1].replace(",", ".")) * factor))} шт`;
  return g >= 1000 ? `${(Math.round(g / 100) / 10).toLocaleString("ru-RU")} кг` : `${Math.round(g / 5) * 5} г`;
}
